"""Write the text the Worker shares with the Python backend to a JSON file.

The Worker (worker/src/contract.ts, worker/src/retrieve.ts) reads this file,
so the system prompt, the failure messages, the excerpt rules, and the
search settings have one source: the Python code.

Run it through the backend's environment:

    uv --directory backend run python scripts/export_contract.py OUT [--check]

With --check it writes nothing and exits 1 if OUT is out of date.
"""

import argparse
import json
import sys
from pathlib import Path

from langchain_core.output_parsers import PydanticOutputParser

from profile_rag.corpus.splitting import HEADING_SEPARATOR
from profile_rag.generation.answer import Answer
from profile_rag.generation.prompt import ATTRIBUTION_MEANINGS, build_prompt
from profile_rag.rag import EXCERPT_CHARS, FAILURES
from profile_rag.retrievers.dense import VISIBLE_VALUES
from profile_rag.retrievers.factory import CANDIDATES, dense_candidates
from profile_rag.retrievers.hybrid import RRF_K
from profile_rag.settings import Settings
from profile_rag.vectorstore.models import BGE_M3
from profile_rag.vectorstore.store import TS_CONFIG

# The Worker searches like the API's default: hybrid mode, `api_k` chunks.
WORKER_K = Settings.model_fields["api_k"].default

EXPECTED_HUMAN = "Evidence:\n{context}\n\nQuestion: {question}"


def contract() -> str:
    """The contract as JSON text, ending in a newline."""
    prompt = build_prompt(PydanticOutputParser(pydantic_object=Answer))
    system, human = prompt.format_messages(context="{context}", question="{question}")
    if human.content != EXPECTED_HUMAN:
        raise SystemExit(f"the human template changed: {human.content!r}; update the Worker")
    data = {
        "_comment": "Generated by backend/scripts/export_contract.py (just worker-contract). "
        "Do not edit.",
        "system": system.content,
        "human": human.content,
        "attributions": list(ATTRIBUTION_MEANINGS),
        "failures": FAILURES,
        "excerpt_chars": EXCERPT_CHARS,
        "heading_separator": HEADING_SEPARATOR,
        "search": {
            "embedding_model": BGE_M3.workers_ai_name,
            "dimensions": BGE_M3.dimensions,
            "query_prefix": BGE_M3.query_prefix,
            "table": BGE_M3.table_name,
            "ts_config": TS_CONFIG,
            "visible": list(VISIBLE_VALUES),
            "k": WORKER_K,
            "candidates": dense_candidates("hybrid", WORKER_K),
            "rrf_k": RRF_K,
        },
    }
    if CANDIDATES < WORKER_K:
        raise SystemExit("CANDIDATES is below k; check retrievers/factory.py")
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = contract()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        sys.exit(0 if current == text else 1)
    args.out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
